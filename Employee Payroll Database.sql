-- Employee Payroll Database

-- Create DEPARTMENTS table
CREATE TABLE DEPARTMENTS(
    DEPT_ID NUMBER PRIMARY KEY,
    DEPT_NAME VARCHAR2(50) NOT NULL
);

-- Create POSITIONS table
CREATE TABLE POSITIONS(
    POSITION_ID NUMBER PRIMARY KEY,
    POSITION_TITLE VARCHAR2(50) NOT NULL,
    MIN_SALARY NUMBER(10 , 2),
    MAX_SALARY NUMBER(10 , 2)
);


-- Create EMPLOYEES table
CREATE TABLE EMPLOYEES(
    EMP_ID NUMBER PRIMARY KEY,
    FIRST_NAME VARCHAR2(50),
    LAST_NAME VARCHAR2(50),
    EMAIL VARCHAR2(100) UNIQUE,
    PHONE VARCHAR2(15),
    HIRE_DATE DATE NOT NULL,
    DEPT_ID NUMBER,
    POSITION_ID NUMBER,
    SALARY NUMBER(10 , 2),
    CONSTRAINT FK_EMP_DEPT FOREIGN KEY(DEPT_ID) REFERENCES DEPARTMENTS(DEPT_ID),
    CONSTRAINT FK_EMP_POS FOREIGN KEY (POSITION_ID) REFERENCES POSITIONS(POSITION_ID)
);

-- Create PAYROLL table
CREATE TABLE PAYROLL (
    PAY_ID        NUMBER PRIMARY KEY,
    EMP_ID        NUMBER,
    PAY_DATE      DATE,
    BASIC_SALARY  NUMBER(10, 2),
    ALLOWANCES    NUMBER(10, 2),
    DEDUCTIONS    NUMBER(10, 2),
    NET_SALARY    NUMBER(10, 2),
    CONSTRAINT FK_PAY_EMP FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEES(EMP_ID)
);

-- Create LEAVE_RECORDS table
CREATE TABLE LEAVE_RECORDS (
    LEAVE_ID     NUMBER PRIMARY KEY,
    EMP_ID       NUMBER,
    START_DATE   DATE,
    END_DATE     DATE,
    LEAVE_TYPE   VARCHAR2(30),
    STATUS       VARCHAR2(20),
    CONSTRAINT FK_LEAVE_EMP FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEES(EMP_ID)
);

